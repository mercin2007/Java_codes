public class Continue1{
    public static void main(String[] args){
        System.out.println("continue Statement:");
        System.out.println("print odd numbers from 1 to 20");
        for(int i=1; i<=20; i++){
            if(i==15){
                 continue;  
                }
            System.out.println(i); 
            }
        }
    }
