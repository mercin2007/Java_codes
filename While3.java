public class While3 {
    static void main(String[] args) {
        System.out.println("While Loop:");
        System.out.println("multiplication table of 7");
        int i = 1;
        while (i <= 10) {
            System.out.println(7 + " * " + i + " = " + (7 * i));
            i++;
        }
    }
}